// Package build concatenates the css/ sources into dist/ui.css, wrapping each
// group in its cascade layer (spec §4.1). Sources contain no @layer of their own.
package build

import (
	"bytes"
	"fmt"
	"io/fs"
	"sort"
	"strings"
)

// Layers is the order every library rule lives in.
var Layers = []string{"ui.reset", "ui.base", "ui.components", "ui.utilities"}

// CSS returns the content of dist/ui.css built from fsys (the repository root).
func CSS(fsys fs.FS) ([]byte, error) {
	comps, err := fs.Glob(fsys, "css/components/*.css")
	if err != nil {
		return nil, fmt.Errorf("build: %w", err)
	}
	sort.Strings(comps)
	groups := [][]string{
		{"css/reset.css"},
		{"css/tokens.css", "css/base.css"},
		comps,
		{"css/utilities.css"},
	}
	var b bytes.Buffer
	b.WriteString("/* ai-ui: generated by `go run ./cmd/build` from css/. Do not edit. */\n")
	fmt.Fprintf(&b, "@layer %s;\n", strings.Join(Layers, ", "))
	for i, files := range groups {
		if len(files) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n@layer %s {\n", Layers[i])
		for _, f := range files {
			src, err := fs.ReadFile(fsys, f)
			if err != nil {
				return nil, fmt.Errorf("build: %w", err)
			}
			fmt.Fprintf(&b, "/* %s */\n", f)
			b.Write(bytes.TrimRight(src, "\n"))
			b.WriteString("\n")
		}
		b.WriteString("}\n")
	}
	return b.Bytes(), nil
}
